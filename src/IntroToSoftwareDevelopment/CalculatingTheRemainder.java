package IntroToSoftwareDevelopment;

public class CalculatingTheRemainder {
    public static void main(String[] args) {
        int remainders = 56 % 6;
        System.out.println("The remainder is " + remainders);

        int remainder = 78 % -4;
        System.out.println("The remainder is " + remainder);

        int remainders1 = -34 % 5;
        System.out.println("The remainder is " + remainders1);

        int remainder2 = -34 % -5;
        System.out.println("The remainder is " + remainder2);

        int remainder3 = 5 % 1;
        System.out.println("The remainder is " + remainder3);

        int remainder4 = 1 % 5;
        System.out.println("The remainder is " + remainder4);

        System.out.println(25.0/4);// question 4 in 2.9 in book

        System.out.println(2 * (5 / 2 + 5 / 2));// question 5 in 2.9 in book
        System.out.println(2 * 5 / 2 + 2 * 5 / 2);
        System.out.println(2 * (5 / 2));
        System.out.println(2 * 5 / 2);

        System.out.println("25 / 4 is " + 25 / 4);// question 6 in 2.9
        System.out.println("25 / 4.0 is " + 25 / 4.0);
        System.out.println("3 * 2 / 4 is " + 3 * 2 / 4);
        System.out.println("3.0 * 2 / 4 is " + 3.0 * 2 / 4);

        System.out.println(Math.pow(2, 3.5));//question 7 in 2.9

        int remainder5 = 25 % 1;
        System.out.println("The remainder is " + remainder5);

        int remainder6 = 2 % 1;
        System.out.println("The remainder is " + remainder6);

        int remainder7 = 15 % 4;
        System.out.println("The remainder is " + remainder7);

        int remainder8 = 37 % 6;
        System.out.println("The remainder is " + remainder8);

        System.out.println(Math.pow(4, 1.5));

    }
}
